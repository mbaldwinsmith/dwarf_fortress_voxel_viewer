export function professionCategories(id: number): string[] {
  const row = professions[id];
  if (!row) return [];
  const out = [row[0]];
  let parent = row[1];
  while (parent && !out.includes(parent)) {
    out.push(parent);
    parent = professions.find((r) => r[0] === parent)?.[1] ?? null;
  }
  return out;
}
